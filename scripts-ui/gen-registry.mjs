import fs from "node:fs";
const root = new URL("../", import.meta.url);
const exists = (p) => fs.existsSync(new URL(p, root));
const read = (p) => JSON.parse(fs.readFileSync(new URL(p, root), "utf8"));
const catalogPath = exists("assets/books/catalog.json")
  ? "assets/books/catalog.json"
  : "src/content/fixtures/catalog.json";
const catalog = read(catalogPath);
const entries = catalog.books
  .filter((b) => exists(`assets/books/${b.id}.json`))
  .map(
    (b) =>
      `${JSON.stringify(b.id)}: () => require('../../assets/books/${b.id}.json')`,
  );
entries.push(`muestra: () => require('./fixtures/sample-book.json')`);
const source = `// Generated by scripts-ui/gen-registry.mjs; Metro requires literal paths.\nexport const catalogData = require('${catalogPath.startsWith("assets") ? "../../assets/books/catalog.json" : "./fixtures/catalog.json"}');\nexport const bookLoaders: Record<string, () => unknown> = {${entries.join(",\n")}};\nexport const glossaryData = require('${exists("assets/glossary.json") ? "../../assets/glossary.json" : "./fixtures/glossary.json"}');\nexport const frasesData = require('${exists("assets/frases.json") ? "../../assets/frases.json" : "./fixtures/frases.json"}');\n`;
fs.writeFileSync(new URL("src/content/registry.ts", root), source);
console.log(`Registry: ${entries.length} books; ${catalogPath}`);
